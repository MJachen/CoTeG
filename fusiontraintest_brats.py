def val_selection_score_macroAUC(val_reports_by_group: dict):
    """
    用于选择 best fusion head：对 k=1..4 的 AUC 做平均（忽略 NaN）
    """
    aucs = []
    for group in val_reports_by_group:
        rep = val_reports_by_group.get(group, None)
        if rep is None:
            continue
        a = rep.get("AUC", float("nan"))
        if not (np.isnan(a) or np.isinf(a)):
            aucs.append(a)
    if len(aucs) == 0:
        return -1.0
    return float(np.mean(aucs))


def get_probs(fusion, zt_cpu, zg_cpu, mask_cpu=None):
    fusion.eval()
    with torch.no_grad():
        mask = None if mask_cpu is None else mask_cpu.to(DEVICE).float()
        logits, _ = fusion(zt_cpu.to(DEVICE).float(), zg_cpu.to(DEVICE).float(), mask)
        prob1 = torch.softmax(logits, dim=1)[:, 1].detach().cpu().numpy()
    return prob1


def report_for_one_k(y_np, prob1, thr):
    d, pred = eval_with_threshold(y_np, prob1, thr)
    return d, pred


def choose_threshold_min_specificity(y_true, prob1, min_spec, thr_grid):
    best_thr = 0.5
    best_detail = None
    best_key = None
    fallback = None
    fallback_key = None
    for thr in thr_grid:
        detail, _ = eval_with_threshold(y_true, prob1, thr)
        key = (
            detail.get("Specificity", float("nan")),
            detail.get("Sensitivity", float("nan")),
            detail.get("F1", detail.get("F1_pos", float("nan"))),
        )
        if fallback is None or key > fallback_key:
            fallback = (float(thr), detail)
            fallback_key = key
        if detail.get("Specificity", 0.0) + 1e-12 < min_spec:
            continue
        cand_key = (
            detail.get("Sensitivity", float("nan")),
            detail.get("F1", detail.get("F1_pos", float("nan"))),
            detail.get("ACC", float("nan")),
        )
        if best_detail is None or cand_key > best_key:
            best_thr = float(thr)
            best_detail = detail
            best_key = cand_key
    if best_detail is None:
        best_thr, best_detail = fallback
    return best_thr, best_detail


def make_balanced_sampler(labels):
    y_np = labels.long().cpu().numpy()
    class_count = np.bincount(y_np, minlength=2).astype(np.float32)
    class_weight = 1.0 / np.clip(class_count, 1.0, None)
    sample_weight = class_weight[y_np]
    return WeightedRandomSampler(
        weights=torch.from_numpy(sample_weight),
        num_samples=len(sample_weight),
        replacement=True,
    )


def summarize_probability_rows(split, groups, y_by_group, prob_by_group):
    rows = []
    for group in groups:
        y = np.asarray(y_by_group[group]).astype(np.int64)
        p = np.asarray(prob_by_group[group]).astype(np.float32)
        row = {
            "split": split,
            "group": group,
            "n": int(len(y)),
            "n_lgg": int((y == 0).sum()),
            "n_hgg": int((y == 1).sum()),
            "prob_min": float(p.min()) if len(p) else float("nan"),
            "prob_max": float(p.max()) if len(p) else float("nan"),
            "prob_mean": float(p.mean()) if len(p) else float("nan"),
            "prob_std": float(p.std()) if len(p) else float("nan"),
        }
        for cls, name in [(0, "lgg"), (1, "hgg")]:
            pc = p[y == cls]
            row[f"prob_{name}_mean"] = float(pc.mean()) if len(pc) else float("nan")
            row[f"prob_{name}_std"] = float(pc.std()) if len(pc) else float("nan")
            row[f"prob_{name}_min"] = float(pc.min()) if len(pc) else float("nan")
            row[f"prob_{name}_max"] = float(pc.max()) if len(pc) else float("nan")
        row.update(compute_auc_pr(y, p))
        rows.append(row)
    return rows


def evaluate_threshold_map(groups, y_by_group, prob_by_group, idx_by_group, threshold_by_group):
    by_group = {}
    sample_tables = []
    y_all, p_all, pred_all = [], [], []
    for group in groups:
        y = np.asarray(y_by_group[group]).astype(np.int64)
        p = np.asarray(prob_by_group[group]).astype(np.float32)
        thr = float(threshold_by_group[group])
        d, pred = eval_with_threshold(y, p, thr)
        d["thr"] = thr
        d["n"] = int(len(y))
        by_group[group] = d
        sample_tables.append(collect_sample_table(y, p, thr, idx_by_group[group], group))
        y_all.append(y)
        p_all.append(p)
        pred_all.append(pred)

    y_all = np.concatenate(y_all, axis=0)
    p_all = np.concatenate(p_all, axis=0)
    pred_all = np.concatenate(pred_all, axis=0)
    tp, fp, tn, fn = confusion_counts(y_all, pred_all)
    overall = derived_metrics_from_conf(tp, fp, tn, fn)
    overall["F1_macro"] = float(f1_score(y_all, pred_all, average="macro"))
    overall["F1"] = overall.get("F1_pos", overall.get("F1", float("nan")))
    overall.update(compute_auc_pr(y_all, p_all))
    overall["thr"] = float("nan")
    overall["n"] = int(len(y_all))
    return overall, by_group, pd.concat(sample_tables, ignore_index=True)


def collect_sample_table(y, prob, thr, idx, group):
    pred = (prob >= thr).astype(int)
    df = pd.DataFrame({
        "idx": idx,
        "modality_group": group,
        "y_true": y,
        "prob_HG": prob,
        "y_pred": pred,
        "correct": (pred == y)
    })
    return df

