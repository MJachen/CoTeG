def compute_roc_points(y_true: np.ndarray, prob1: np.ndarray):
    """
    Returns fpr, tpr, thresholds (numpy arrays) for ROC.
    Note: roc_curve expects labels in {0,1}.
    """
    fpr, tpr, thr = roc_curve(y_true.astype(int), prob1.astype(float), pos_label=1)
    return fpr, tpr, thr


def save_roc_txt(txt_path: str, all_models: list):
    """
    all_models: list of dict, each dict:
      {
        "model_name": str,
        "thr_mode": str,          # "overall" or "per_k"
        "k": int,
        "thr_used": float,
        "idx": np.ndarray (N,),
        "y_true": np.ndarray (N,),
        "prob1": np.ndarray (N,),
        "roc_fpr": np.ndarray,
        "roc_tpr": np.ndarray,
        "roc_thr": np.ndarray,
      }

    Write as a single TXT file with two sections per model:
      - [RAW] idx y_true prob1
      - [ROC] fpr tpr thr
    """
    with open(txt_path, "w", encoding="utf-8") as f:
        f.write("# ROC export file\n")
        f.write("# Each model block contains:\n")
        f.write("#   [RAW] rows: idx<TAB>y_true<TAB>prob1\n")
        f.write("#   [ROC] rows: fpr<TAB>tpr<TAB>thr\n\n")

        for m in all_models:
            f.write("============================================================\n")
            f.write(f"MODEL_NAME:\t{m['model_name']}\n")
            f.write(f"THR_MODE:\t{m['thr_mode']}\n")
            f.write(f"K:\t{m['k']}\n")
            f.write(f"THR_USED:\t{m['thr_used']:.10f}\n")
            f.write(f"N:\t{len(m['y_true'])}\n")

            # --- RAW ---
            f.write("[RAW]\n")
            f.write("idx\ty_true\tprob1\n")
            idx = m["idx"]
            y = m["y_true"]
            p = m["prob1"]
            for i in range(len(y)):
                f.write(f"{int(idx[i])}\t{int(y[i])}\t{float(p[i]):.10f}\n")

            # --- ROC points ---
            f.write("[ROC]\n")
            f.write("fpr\ttpr\tthr\n")
            fpr = m["roc_fpr"]
            tpr = m["roc_tpr"]
            thr = m["roc_thr"]
            for i in range(len(fpr)):
                f.write(f"{float(fpr[i]):.10f}\t{float(tpr[i]):.10f}\t{float(thr[i]):.10f}\n")

            f.write("\n")

