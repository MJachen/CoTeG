    diag["unique_masks"] = ";".join(",".join(str(v) for v in row) for row in unique_masks)

    fac = torch.load(tucker_path, map_location="cpu")
    if "U_N" not in fac:
        raise KeyError(f"{tucker_path} missing key 'U_N'")
