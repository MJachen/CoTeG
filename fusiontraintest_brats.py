class MoEFusion(nn.Module):
    def __init__(self, dim_t, dim_g, hidden, num_classes, p=0.3, mask_dim=4):
        super().__init__()
        self.mask_dim = int(mask_dim)
        self.proj_t = nn.Sequential(nn.Linear(dim_t, hidden), nn.LayerNorm(hidden))
        self.proj_g = nn.Sequential(nn.Linear(dim_g, hidden), nn.LayerNorm(hidden))

        self.expert_t = nn.Sequential(nn.Linear(hidden, 64), nn.ReLU(True), nn.Dropout(p), nn.Linear(64, num_classes))
        self.expert_g = nn.Sequential(nn.Linear(hidden, 64), nn.ReLU(True), nn.Dropout(p), nn.Linear(64, num_classes))

        self.gate = nn.Sequential(
            nn.Linear(hidden * 4 + self.mask_dim, 32),
            nn.ReLU(True),
            nn.Linear(32, 1)
        )

    def forward(self, ft, fg, mask=None):
        ft = self.proj_t(ft)
        fg = self.proj_g(fg)

        z = torch.cat([ft, fg, (ft - fg).abs(), ft * fg], dim=1)
        if self.mask_dim > 0:
            if mask is None:
                mask = torch.zeros((z.size(0), self.mask_dim), dtype=z.dtype, device=z.device)
            z = torch.cat([z, mask.to(device=z.device, dtype=z.dtype)], dim=1)
        alpha = torch.sigmoid(self.gate(z))  # (N,1)

        logit_t = self.expert_t(ft)
        logit_g = self.expert_g(fg)
        logits = alpha * logit_t + (1 - alpha) * logit_g
        return logits, alpha


class ConcatFusion(nn.Module):
    def __init__(self, dim_t, dim_g, hidden, num_classes, p=0.3, mask_dim=4):
        super().__init__()
        self.mask_dim = int(mask_dim)
        in_dim = int(dim_t) + int(dim_g) + self.mask_dim
        self.head = nn.Sequential(
            nn.Linear(in_dim, hidden),
            nn.LayerNorm(hidden),
            nn.ReLU(True),
            nn.Dropout(p),
            nn.Linear(hidden, 64),
            nn.ReLU(True),
            nn.Dropout(p),
            nn.Linear(64, num_classes),
        )

    def forward(self, ft, fg, mask=None):
        xs = [ft, fg]
        if self.mask_dim > 0:
            if mask is None:
                mask = torch.zeros((ft.size(0), self.mask_dim), dtype=ft.dtype, device=ft.device)
            xs.append(mask.to(device=ft.device, dtype=ft.dtype))
        logits = self.head(torch.cat(xs, dim=1))
        alpha = torch.full((ft.size(0), 1), float("nan"), dtype=ft.dtype, device=ft.device)
        return logits, alpha


class SingleBranchHead(nn.Module):
    def __init__(self, in_dim, hidden, num_classes, p=0.3):
        super().__init__()
        self.head = nn.Sequential(
            nn.Linear(in_dim, hidden),
            nn.LayerNorm(hidden),
            nn.ReLU(True),
            nn.Dropout(p),
            nn.Linear(hidden, 64),
            nn.ReLU(True),
            nn.Dropout(p),
            nn.Linear(64, num_classes),
        )


class TensorOnlyHead(SingleBranchHead):
    def forward(self, ft, fg, mask=None):
        logits = self.head(ft)
        alpha = torch.ones((ft.size(0), 1), dtype=ft.dtype, device=ft.device)
        return logits, alpha


class GNNOnlyHead(SingleBranchHead):
    def forward(self, ft, fg, mask=None):
        logits = self.head(fg)
        alpha = torch.zeros((fg.size(0), 1), dtype=fg.dtype, device=fg.device)
        return logits, alpha


def build_fusion_model(mode, dim_t, dim_g):
    mask_dim = 4 if FUSION_USE_MASK else 0
    if mode == "moe":
        return MoEFusion(
            dim_t=dim_t,
            dim_g=dim_g,
            hidden=FUSION_HIDDEN,
            num_classes=2,
            p=FUSION_DROPOUT,
            mask_dim=mask_dim,
        )
    if mode == "concat":
        return ConcatFusion(
            dim_t=dim_t,
            dim_g=dim_g,
            hidden=FUSION_HIDDEN,
            num_classes=2,
            p=FUSION_DROPOUT,
            mask_dim=mask_dim,
        )
    if mode == "tensor_only":
        return TensorOnlyHead(
            in_dim=dim_t,
            hidden=FUSION_HIDDEN,
            num_classes=2,
            p=FUSION_DROPOUT,
        )
    if mode == "gnn_only":
        return GNNOnlyHead(
            in_dim=dim_g,
            hidden=FUSION_HIDDEN,
            num_classes=2,
            p=FUSION_DROPOUT,
        )
    raise ValueError("FUSION_MODE must be one of: moe, concat, tensor_only, gnn_only")
